#!/usr/bin/env node
// Generate the Hangul command coverage list and shortcut map (spec task 0.6).
//
//   node scripts/hangul-coverage.mjs <path to an rhwp checkout at the pinned tag>
//
// rhwp-studio's command registry is the baseline: 163 commands named after
// 한글's own menus, with 한글-compatible shortcuts. The output is the list the
// new editor must reach (R5.3, checked by task 2.6) and the shortcuts it must
// bind (R4.2, task 1.6). Each command carries a `hancom2024` field to be set
// once the list is reconciled with 한글 2024's menus on the runner (P-1):
// "present", "absent" (in rhwp-studio but not in 한글 2024), or a note.
// 한글 2024 menu items that rhwp-studio lacks are added by hand with
// `"source": "hancom2024"`; the script keeps those rows when it regenerates.
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const upstream = process.argv[2]
if (!upstream || !existsSync(join(upstream, 'rhwp-studio/src/command'))) {
  console.error('usage: hangul-coverage.mjs <rhwp checkout>')
  process.exit(2)
}
const provenance = JSON.parse(readFileSync(join(root, 'packages/hwp-core/provenance.json'), 'utf8'))
const studio = join(upstream, 'rhwp-studio/src')
const outDir = join(root, '.kiro/specs/hangul-editor/coverage')
mkdirSync(outDir, { recursive: true })

function locale(name) {
  const text = readFileSync(join(studio, `i18n/locales/${name}.ts`), 'utf8')
  const map = {}
  for (const m of text.matchAll(/^\s*"([^"]+)":\s*"((?:[^"\\]|\\.)*)",?\s*$/gm)) map[m[1]] = JSON.parse(`"${m[2]}"`)
  return map
}
const ko = locale('ko')
const en = locale('en')

// ── Commands ────────────────────────────────────────────────────────────
const commands = []
const dir = join(studio, 'command/commands')
for (const file of readdirSync(dir).filter((f) => f.endsWith('.ts')).sort()) {
  const text = readFileSync(join(dir, file), 'utf8')
  // Each command object starts with `id: '<ns>:<action>'`; read the fields up to the next id.
  const starts = [...text.matchAll(/\bid:\s*'([a-z0-9]+:[a-z0-9:_.-]+)'/g)]
  for (const [i, m] of starts.entries()) {
    const body = text.slice(m.index, starts[i + 1]?.index ?? text.length)
    const labelKey = body.match(/\blabel:\s*t\('([^']+)'\)/)?.[1]
    const literal = body.match(/\blabel:\s*'([^']+)'/)?.[1]
    commands.push({
      id: m[1],
      group: m[1].split(':')[0],
      ko: labelKey ? (ko[labelKey] ?? null) : (literal ?? null),
      en: labelKey ? (en[labelKey] ?? null) : null,
      shortcut: body.match(/\bshortcutLabel:\s*'([^']+)'/)?.[1] ?? null,
      dialog: /Dialog\b/.test(body.split(/\bexecute\b/)[1] ?? '') || null,
      source: 'rhwp-studio',
      hancom2024: null,
    })
  }
}
const ids = new Set()
const unique = commands.filter((c) => (ids.has(c.id) ? false : (ids.add(c.id), true)))

// Keep hand-added 한글 2024 rows and any reconciliation already recorded.
const commandsPath = join(outDir, 'commands.json')
if (existsSync(commandsPath)) {
  const prior = JSON.parse(readFileSync(commandsPath, 'utf8')).commands
  const byId = new Map(prior.map((c) => [c.id, c]))
  for (const c of unique) if (byId.get(c.id)?.hancom2024) c.hancom2024 = byId.get(c.id).hancom2024
  for (const c of prior) if (c.source === 'hancom2024' && !ids.has(c.id)) unique.push(c)
}

// ── Shortcuts ───────────────────────────────────────────────────────────
const mapText = readFileSync(join(studio, 'command/shortcut-map.ts'), 'utf8')
const shortcuts = []
for (const m of mapText.matchAll(/\[\s*\{([^}]*)\}\s*,\s*'([a-z0-9]+:[a-z0-9:_.-]+)'\s*\]/g)) {
  const def = {}
  for (const kv of m[1].matchAll(/(\w+):\s*('([^']*)'|true|false)/g)) def[kv[1]] = kv[3] ?? kv[2] === 'true'
  shortcuts.push({ ...def, command: m[2] })
}

const header = {
  generatedFrom: `${provenance.upstream.repository} ${provenance.upstream.tag} (${provenance.upstream.commit}) rhwp-studio/src/command`,
  note: 'Baseline from rhwp-studio. Reconcile with 한글 2024 menus on the runner: set hancom2024 per row; add missing 한글 2024 items with source "hancom2024".',
}
writeFileSync(commandsPath, JSON.stringify({ ...header, count: unique.length, commands: unique }, null, 2) + '\n')
writeFileSync(join(outDir, 'shortcuts.json'), JSON.stringify({ ...header, count: shortcuts.length, shortcuts }, null, 2) + '\n')

const groups = {}
for (const c of unique) groups[c.group] = (groups[c.group] ?? 0) + 1
const md = [
  '# Hangul command coverage (generated)',
  '',
  `Generated by \`scripts/hangul-coverage.mjs\` from ${header.generatedFrom}. Do not edit by hand except the`,
  '`hancom2024` field and rows with `"source": "hancom2024"` in `commands.json`.',
  '',
  `${unique.length} commands, ${shortcuts.length} shortcut bindings.`,
  '',
  '| Group | Commands |',
  '| --- | --- |',
  ...Object.entries(groups).map(([g, n]) => `| ${g} | ${n} |`),
  '',
  '| Id | 한국어 | English | Shortcut |',
  '| --- | --- | --- | --- |',
  ...unique.map((c) => `| \`${c.id}\` | ${c.ko ?? ''} | ${c.en ?? ''} | ${c.shortcut ?? ''} |`),
  '',
]
writeFileSync(join(outDir, 'README.md'), md.join('\n'))
console.log(`coverage: ${unique.length} commands, ${shortcuts.length} shortcuts → ${outDir}`)
